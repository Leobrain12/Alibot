-- ТЗ п.132 — справочники переезжают из статичного конфига (CatalogProperties) в БД, чтобы
-- SUPERADMIN мог редактировать их через интерфейс. Сиды ниже — те же значения, что раньше жили
-- в CatalogProperties (значения по умолчанию), так что поведение бота/Mini App не меняется сразу
-- после миграции.
--
-- UUID заданы литералами, а не gen_random_uuid()/random_uuid() — эти функции не совпадают между
-- H2 и PostgreSQL без явных расширений (см. историю с "clob" в V1 — та же ловушка портируемости).

create table reference_items (
    id uuid primary key,
    category varchar(40) not null,
    -- "value" зарезервировано в H2 (конфликтует с VALUES/NEXT VALUE FOR) — называем колонку
    -- иначе, чтобы не зависеть от кавычек идентификатора в разных СУБД.
    item_value varchar(255) not null,
    sort_order int not null default 0,
    active boolean not null default true
);
create unique index uq_reference_items_category_value on reference_items(category, item_value);
create index idx_reference_items_category on reference_items(category, active);

